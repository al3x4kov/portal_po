/**
 * Чистка имён, приходящих от модели (AI-импорт документации).
 *
 * Модель иногда отдаёт вместо имени служебный мусор: строку `"null"` там, где
 * ожидался JSON-`null`, или имя с приклеенным хвостом собственного ответа —
 * `«Доступность и надежность → null}, {»`. Zod такие значения пропускает
 * (это непустые строки ≤ 200 символов), и портал создаёт требование с именем
 * «null» — ровно то, что бросается в глаза в журнале импорта.
 *
 * Правило детерминированное и не зависит от модели: сначала отрезаем заведомо
 * машинные хвосты, затем сверяем остаток со списком слов-заглушек. Всё, что
 * не похоже на имя, отбраковывается (`null`), а не «чинится» догадками.
 */

/** Слова-заглушки: имя из них одних не несёт смысла. */
const PLACEHOLDER_NAMES = new Set([
  'null',
  'undefined',
  'none',
  'nan',
  'nil',
  'n/a',
  'na',
  '-',
  '—',
  '–',
  '?',
  '...',
  '…',
]);

/**
 * Символы протёкшего JSON. Встретив любой из них, обрезаем строку по нему:
 * в имени бизнес-домена фигурные/квадратные скобки и кавычки не нужны, зато
 * они однозначно выдают приклеенный хвост ответа модели.
 */
const JSON_TAIL_RE = /[{}[\]"]/;

/**
 * Разделитель «имя → родитель» из табличного рендера таксономии в промпте:
 * модель порой копирует формат целиком. Берём часть ДО стрелки.
 */
const ARROW_RE = /\s*(?:→|->)\s*/;

/**
 * Привести имя от модели к пригодному виду или отбраковать его.
 *
 * @returns очищенное имя либо `null`, если после чистки не осталось смысла.
 */
export function sanitizeAiName(raw: string): string | null {
  const unquote = (value: string): string =>
    value
      .trim()
      .replace(/^[«"'`]+/, '')
      .replace(/[»"'`]+$/, '')
      .replace(/[,;:]+$/, '')
      .trim();

  // 1. Снять обрамляющие кавычки — иначе они сами выглядят как хвост JSON.
  let name = unquote(raw.replace(/\s+/g, ' '));

  // 2. Отрезать приклеенный хвост JSON и скопированный формат «имя → родитель».
  const jsonAt = name.search(JSON_TAIL_RE);
  if (jsonAt >= 0) name = name.slice(0, jsonAt);
  const arrowAt = name.search(ARROW_RE);
  if (arrowAt >= 0) name = name.slice(0, arrowAt);

  // 3. Повторная чистка краёв: обрезка могла обнажить новую пунктуацию.
  name = unquote(name);

  if (name.length === 0) return null;
  // 3. Заглушки и строки без единой буквы/цифры именем быть не могут.
  if (PLACEHOLDER_NAMES.has(name.toLowerCase())) return null;
  if (!/[\p{L}\p{N}]/u.test(name)) return null;
  return name;
}

/**
 * Родитель от модели: строковый `"null"` (и прочие заглушки) означает
 * «родителя нет», а не домен с таким именем — иначе в дереве появляется
 * корневой узел «null».
 */
export function sanitizeAiParentName(raw: string | null | undefined): string | null {
  if (raw === null || raw === undefined) return null;
  return sanitizeAiName(raw);
}
